def run() -> int:
    import re
    failures = []
    for name, lines, rendered, must_flag in CASES:
        pdf = re.sub(r"\s+", " ", rendered)
        tmp = HERE / "_fixture.tex"
        tmp.write_text("\n".join(lines) + "\n", encoding="utf8")
        try:
            hits = ctp.suspects_in(tmp, pdf)
        finally:
            tmp.unlink(missing_ok=True)
        flagged = bool(hits)
        ok = flagged == must_flag
        print(f"{'PASS' if ok else 'FAIL'}  {'flag' if must_flag else 'quiet':5s}  {name}")
        if not ok:
            failures.append(name)
            for h in hits:
                print(f"        unexpected hit: line {h[0]} tail={h[1][:70]!r}")
    print(f"\n{len(CASES) - len(failures)}/{len(CASES)} fixtures pass")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(run())
